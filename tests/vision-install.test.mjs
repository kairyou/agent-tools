test("zcode vision manages native MCP config and the user skill", () => {
  const dir = tmp();
  const home = join(dir, "agent-tools-home");
  const config = join(dir, "zcode", "cli", "config.json");
  const skillsDir = join(dir, "zcode", "skills");
  mkdirSync(join(dir, "zcode", "cli"), { recursive: true });
  writeFileSync(
    config,
    '{\n  // keep this comment\n  "theme": "dark",\n  "mcp": { "servers": { "other": { "command": "keep" } } }\n}\n'
  );
  const args = [
    "vision", "-a", "zcode",
    "--zcode-config", config,
    "--zcode-skills-dir", skillsDir,
  ];
  const env = { AGENT_TOOLS_HOME: home };

  runInstall(args, env);
  let text = readFileSync(config, "utf8");
  let cfg = parseJsonc(text);
  assert.match(text, /keep this comment/);
  assert.equal(cfg.theme, "dark");
  assert.equal(cfg.mcp.servers.other.command, "keep");
  assert.deepEqual(cfg.mcp.servers["agent-tools-vision"], {
    command: "node",
    args: [runtimeServerPath(home)],
    env: {},
  });
  assert.ok(existsSync(join(skillsDir, "at-vision", "SKILL.md")));

  runInstall(args, env);
  runInstall([...args, "--uninstall"], env);
  text = readFileSync(config, "utf8");
  cfg = parseJsonc(text);
  assert.match(text, /keep this comment/);
  assert.equal(cfg.mcp.servers["agent-tools-vision"], undefined);
  assert.equal(cfg.mcp.servers.other.command, "keep");
  assert.ok(!existsSync(join(skillsDir, "at-vision")));
  assert.ok(!existsSync(join(home, "dist", "vision")));
});

