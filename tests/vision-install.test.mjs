test("pi vision installs a native extension stub, runtime, and skill", () => {
  const dir = tmp();
  const home = join(dir, "agent-tools-home");
  const agentDir = join(dir, "pi-agent");
  const args = ["vision", "-a", "pi", "--pi-agent-dir", agentDir];
  const env = { AGENT_TOOLS_HOME: home };

  runInstall(args, env);
  const stub = join(agentDir, "extensions", "agent-tools-vision.js");
  const skill = join(agentDir, "skills", "at-vision", "SKILL.md");
  const extension = join(home, "dist", "vision", "pi-extension.mjs");
  assert.ok(existsSync(stub));
  assert.match(readFileSync(stub, "utf8"), /Generated by agent-tools installer/);
  assert.match(readFileSync(stub, "utf8"), /pi-extension\.mjs/);
  assert.ok(existsSync(extension));
  assert.ok(existsSync(skill));

  runInstall(args, env);
  runInstall([...args, "--uninstall"], env);
  assert.ok(!existsSync(stub));
  assert.ok(!existsSync(join(agentDir, "skills", "at-vision")));
  assert.ok(!existsSync(join(home, "dist", "vision")));
});

